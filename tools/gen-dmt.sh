#!/bin/bash
# Генерирует internal/timing/dmt_table.go из edid-decode --dmt.
set -e
out=${1:-internal/timing/dmt_table.go}
{
echo "// Code generated by tools/gen-dmt.sh from edid-decode --dmt. DO NOT EDIT."
echo
echo "package timing"
echo
echo "var dmtTable = []Mode{"
for id in $(edid-decode --list-dmts | awk '{print $2}' | tr -d ':'); do
  edid-decode --dmt "$id" | awk -v id="$id" '
    NR==1 { split($3,r,"x"); w=r[1]; h=r[2]; for (i=1;i<=NF;i++) if ($i=="MHz") clk=$(i-1); il=($3 ~ /i$/) ? "true" : "false"; rb=($0 ~ /\(RB/) ? "true" : "false" }
    /Hfront/ { hf=$2+$10; hs=$4; hb=$6+$10; hp=$8 }
    /Vfront/ { vf=$2+$10; vs=$4; vb=$6+$10; vp=$8 }
    END {
      if (il=="true") exit
      printf "\t{Source: \"DMT %s\", PixelClock: %s, HActive: %d, HSyncStart: %d, HSyncEnd: %d, HTotal: %d, VActive: %d, VSyncStart: %d, VSyncEnd: %d, VTotal: %d, HSyncPos: %s, VSyncPos: %s, Interlaced: %s, Reduced: %s},\n",
        id, clk*1000, w, w+hf, w+hf+hs, w+hf+hs+hb, h, h+vf, h+vf+vs, h+vf+vs+vb, (hp=="P")?"true":"false", (vp=="P")?"true":"false", il, rb
    }'
done
echo "}"
} > "$out"
gofmt -w "$out"
